export type SpriteName = keyof typeof SPRITES;

/** One SVG path for a sprite: each horizontal run of lit pixels becomes a rectangle. */
export function spritePath(name: SpriteName) {
  const rows = SPRITES[name];
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '1') {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === '1') end++;
      d += `M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end;
    }
  });
  const w = Math.max(...rows.map((r) => r.length));
  const side = Math.max(w, rows.length);
  // Centre the bitmap in a square box so every icon sits on the same grid.
  const ox = Math.floor((side - w) / 2);
  const oy = Math.floor((side - rows.length) / 2);
  return { d, side, ox, oy };
}
